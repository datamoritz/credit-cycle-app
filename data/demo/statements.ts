export const getStatementsByCardId = (cardId: string): Statement[] =>
  STATEMENTS.filter((s) => s.cardId === cardId).sort((a, b) =>
    b.statementMonth.localeCompare(a.statementMonth)
  );

export const getStatementsByMonth = (month: string): Statement[] =>
  STATEMENTS.filter((s) => {
    // Return statements whose payment is due in the given month
    return s.dueDate.startsWith(month.substring(0, 7));
  });
